// Generate cordis.patch.yml from `dsh --profile web --dump-default-config` output:
//   - the host row;
//   - an override of the shipped `standard` preset: its rows unchanged, plus the rule row, so every
//     ordinary session can switch scheduling on with `/schedule` or the composer switch;
//   - the retired `scheduler` preset, kept only so Sessions created with it still open. Its rule
//     row sets `defaultOn`, matching how those Sessions behaved.
// usage: node scripts/gen-preset.mjs <dump.yml>
import { readFileSync, writeFileSync } from 'node:fs'

const lines = readFileSync(process.argv[2], 'utf8').split('\n')
const from = lines.indexOf('- id: preset-standard')
const to = lines.findIndex((l, i) => i > from && l.startsWith('- id: '))
if (from < 0 || to < 0) throw new Error('preset-standard not found in dump')
// Keep blank lines: they are paragraph breaks inside folded scalars (the plan-mode section).
const block = lines.slice(from, to)
while (block.at(-1)?.trim() === '') block.pop()
const config = block.indexOf('  config:')
const pluginsAt = block.indexOf('    plugins:')
if (config < 0 || pluginsAt < 0) throw new Error('standard preset has no plugins')
const head = block.slice(config + 1, pluginsAt).filter(l => !/^ {4}(name|description):/u.test(l))
if (!head.includes('    id: standard')) throw new Error('unexpected standard preset header')
const rows = block.slice(pluginsAt + 1)
const rule = (defaultOn) => [
  '      - id: agent-scheduler-rule',
  '        name: dsh-agent-scheduler/rule',
  `        config: ${defaultOn ? '{ defaultOn: true }' : '{}'}`,
]
writeFileSync('cordis.patch.yml', [
  '# GENERATED by scripts/gen-preset.mjs from dsh 0.2.1-rc.5 `--dump-default-config`; do not edit by hand.',
  '# Overrides the shipped standard preset (its rows unchanged, plus the scheduler rule).',
  "- id: preset-standard",
  "  name: '@deepseek-ai/dsh-agent-preset'",
  '  config:',
  ...head,
  '    plugins:',
  ...rule(false),
  ...rows,
  '- insert:',
  '    - id: dsh-agent-scheduler',
  '      name: dsh-agent-scheduler',
  '      config: {}',
  '    # Retired: kept so Sessions created in it still open. New sessions use the standard preset.',
  '    - id: preset-scheduler',
  "      name: '@deepseek-ai/dsh-agent-preset'",
  '      config:',
  '        id: scheduler',
  '        name: 调度（旧会话）',
  '        order: 99',
  '        description: 已停用。新会话用默认预设，在输入框底栏打开「调度」。',
  '        plugins:',
  ...rule(true).map(l => `    ${l}`),
  ...rows.map(l => l.trim() === '' ? '' : `    ${l}`),
  '',
].join('\n'))
