// Generate cordis.patch.yml: the host row plus a `scheduler` preset that copies the standard
// preset's rows from `dsh --dump-config` output and adds the rule row.
// usage: node scripts/gen-preset.mjs <dump.yml>
import { readFileSync, writeFileSync } from 'node:fs'

const lines = readFileSync(process.argv[2], 'utf8').split('\n')
const from = lines.indexOf('- id: preset-standard')
const to = lines.findIndex((l, i) => i > from && l.startsWith('- id: '))
if (from < 0 || to < 0) throw new Error('preset-standard not found in dump')
const body = lines.slice(from + 1, to)
const pluginsAt = body.indexOf('    plugins:')
if (pluginsAt < 0) throw new Error('standard preset has no plugins')
const rows = body.slice(pluginsAt + 1).map(l => `    ${l}`)
writeFileSync('cordis.patch.yml', [
  '# GENERATED by scripts/gen-preset.mjs from dsh 0.2.1-rc.5 `--dump-config`; do not edit by hand.',
  '- insert:',
  '    - id: dsh-agent-scheduler',
  '      name: dsh-agent-scheduler',
  '      config: {}',
  '    - id: preset-scheduler',
  "      name: '@deepseek-ai/dsh-agent-preset'",
  '      config:',
  '        id: scheduler',
  '        name: 调度模式',
  '        order: 5',
  '        description: 每条输入交给一个分身，lead 不被占住。',
  '        plugins:',
  '          - id: agent-scheduler-rule',
  '            name: dsh-agent-scheduler/rule',
  '            config: {}',
  ...rows,
  '',
].join('\n'))
